<#
.SYNOPSIS
    Iterates over all .p7m files in a folder and displays the recipient key identifiers.

.DESCRIPTION
    This script scans a specified folder for S/MIME PKCS#7 encrypted files (.p7m).
    For each file, it reads the EnvelopedCms envelope and inspects the RecipientInfos
    collection to display the recipient identifiers (Issuer/Serial Number or SKI)
    and encryption algorithms required to decrypt the message.
    It also checks the local certificate store to see if a matching private key is available.

.PARAMETER FolderPath
    The path to the folder containing .p7m files.
    This parameter is mandatory.

.PARAMETER KeyJsonPath
    The path to a JSON file containing certificate records exported from PFX/P12 files
    (e.g., generated by print-keys-frm-pfx.ps1). If provided, the script will check
    for matching serial numbers between the message recipients and this JSON file.

.EXAMPLE
    .\print-recip-keys-frm-msg.ps1 -FolderPath "C:\EncryptedEmails"

.EXAMPLE
    .\print-recip-keys-frm-msg.ps1 -FolderPath "C:\EncryptedEmails" -KeyJsonPath ".\key-serials.json"

.NOTES
    Requires: PowerShell 5.1+ or PowerShell Core 7+
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true, Position = 0)]
    [ValidateScript({ Test-Path $_ -PathType Container })]
    [string]$FolderPath,

    [Parameter(Position = 1)]
    [ValidateScript({ Test-Path $_ -PathType Leaf })]
    [string]$KeyJsonPath
)

# Ensure the required cryptography assembly is loaded
Add-Type -AssemblyName System.Security

# Load and parse key records from JSON file if provided
$importedKeys = @()
if ($KeyJsonPath) {
    try {
        $rawJson = Get-Content -Path $KeyJsonPath -Raw -ErrorAction Stop
        $parsedJson = $rawJson | ConvertFrom-Json
        # Handle both single-object and array JSON structures
        $importedKeys = @($parsedJson)
        Write-Host "Loaded $($importedKeys.Count) key record(s) from $KeyJsonPath" -ForegroundColor Green
    }
    catch {
        Write-Host "Error reading key JSON file '$KeyJsonPath': $_" -ForegroundColor Red
        return
    }
}

# Helper to normalize serial numbers for comparison (remove spaces/dashes and uppercase)
function normalizeSerialNumber ([string]$serial) {
    if (-not $serial) { return "" }
    return ($serial -replace '[\s\-:]', '').ToUpperInvariant()
}

# Get all .p7m files in the folder
$p7mFiles = Get-ChildItem -Path $FolderPath -Filter *.p7m -File

if (-not $p7mFiles) {
    Write-Host "No .p7m files found in $FolderPath" -ForegroundColor Yellow
    return
}

foreach ($file in $p7mFiles) {
    Write-Host "`n=== Processing: $($file.FullName) ===" -ForegroundColor Cyan

    try {
        $fileBytes = [System.IO.File]::ReadAllBytes($file.FullName)

        # Parse the CMS/PKCS#7 EnvelopedData structure
        $envelopedCms = New-Object System.Security.Cryptography.Pkcs.EnvelopedCms
        $envelopedCms.Decode($fileBytes)

        $recipients = $envelopedCms.RecipientInfos

        if ($recipients.Count -eq 0) {
            Write-Host "No recipient information found in message." -ForegroundColor Yellow
            continue
        }

        Write-Host "Total Recipients: $($recipients.Count)" -ForegroundColor Green

        $index = 1
        foreach ($recipient in $recipients) {
            Write-Host "`n  [Recipient #$index]" -ForegroundColor White
            Write-Host "  Type:                   $($recipient.Type)"
            Write-Host "  Key Encryption Alg:     $($recipient.KeyEncryptionAlgorithm.Oid.FriendlyName) ($($recipient.KeyEncryptionAlgorithm.Oid.Value))"

            $identifier = $recipient.RecipientIdentifier
            Write-Host "  Identifier Type:        $($identifier.Type)"

            switch ($identifier.Type) {
                ([System.Security.Cryptography.Pkcs.SubjectIdentifierType]::IssuerAndSerialNumber) {
                    $issuerSerial = $identifier.Value
                    Write-Host "  Issuer Name:            $($issuerSerial.IssuerName)"
                    Write-Host "  Serial Number:          $($issuerSerial.SerialNumber)"

                    # Check input JSON file for matching certificate serial number
                    if ($importedKeys.Count -gt 0) {
                        $normMsgSerial = normalizeSerialNumber $issuerSerial.SerialNumber
                        $jsonMatch = $importedKeys | Where-Object {
                            (normalizeSerialNumber $_.SerialNumber) -eq $normMsgSerial
                        }

                        if ($jsonMatch) {
                            foreach ($match in $jsonMatch) {
                                Write-Host "  JSON Match Found:       $($match.Subject) [File: $($match.FileName)] (Has Private Key: $($match.HasPrivateKey))" -ForegroundColor Green
                            }
                        } else {
                            Write-Host "  No JSON Match Found:       No match found in $KeyJsonPath" -ForegroundColor DarkGray
                        }
                    }

                    # Check current user store for matching certificate
                    $localCert = Get-ChildItem -Path Cert:\CurrentUser\My | Where-Object {
                        $_.SerialNumber -eq $issuerSerial.SerialNumber
                    }
                    if ($localCert) {
                        Write-Host "  Local Match Found:      $($localCert.Subject) (Has Private Key: $($localCert.HasPrivateKey))" -ForegroundColor Green
                    } else {
                        Write-Host "  No Local Match Found:      No matching certificate in CurrentUser\My" -ForegroundColor DarkGray
                    }
                }
                ([System.Security.Cryptography.Pkcs.SubjectIdentifierType]::SubjectKeyIdentifier) {
                    $ski = $identifier.Value
                    Write-Host "  Subject Key Identifier: $ski"

                    # Check input JSON file for matching certificate SKI if available in extensions
                    if ($importedKeys.Count -gt 0) {
                        $cleanSki = ($ski -replace '[\s\-:]', '').ToUpperInvariant()
                        $jsonMatch = $importedKeys | Where-Object {
                            $matchFound = $false
                            if ($_.Extensions) {
                                foreach ($ext in $_.Extensions) {
                                    if ($ext.OidValue -eq "2.5.29.14" -or $ext.OidFriendlyName -eq "Subject Key Identifier") {
                                        $cleanExtVal = ($ext.Value -replace '[\s\-:]', '').ToUpperInvariant()
                                        if ($cleanExtVal -eq $cleanSki) {
                                            $matchFound = $true
                                            break
                                        }
                                    }
                                }
                            }
                            $matchFound
                        }

                        if ($jsonMatch) {
                            foreach ($match in $jsonMatch) {
                                Write-Host "  JSON Match Found:       $($match.Subject) [File: $($match.FileName)] (Has Private Key: $($match.HasPrivateKey))" -ForegroundColor Green
                            }
                        } else {
                            Write-Host "  No JSON Match Found:      No SKI match found in $KeyJsonPath" -ForegroundColor DarkGray
                        }
                    }

                    # Check current user store for matching SKI
                    $localCert = Get-ChildItem -Path Cert:\CurrentUser\My | Where-Object {
                        ($_.Extensions | Where-Object { $_.Oid.Value -eq "2.5.29.14" } | ForEach-Object { $_.Format(0) }) -eq $ski
                    }
                    if ($localCert) {
                        Write-Host "  Local Match Found:      $($localCert.Subject) (Has Private Key: $($localCert.HasPrivateKey))" -ForegroundColor Green
                    } else {
                        Write-Host "  No Local Match Found:      No matching certificate in CurrentUser\My" -ForegroundColor DarkGray
                    }
                }
                Default {
                    Write-Host "  Identifier Value:       $($identifier.Value)"
                }
            }
            $index++
        }
    }
    catch {
        Write-Host "Error parsing $($file.Name): $_" -ForegroundColor Red
    }
}
